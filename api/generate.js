const MODEL = process.env.OPENAI_MODEL || "gpt-5.6";

const TASKS = {
  reels: `Создай готовый сценарий Reels, который реально можно снять, а не описание идеи. Верни:
1) сильный hook в первые 1–2 секунды;
2) покадровый план с конкретными действиями;
3) точный текст, который говорит автор или диктор;
4) текст на экране;
5) CTA, соответствующий цели.
Учитывай указанную длину. Не используй пустые фразы вроде «покажи продукт», «расскажи о пользе», «начни с боли» без конкретного текста.`,
  post: `Напиши полноценный готовый пост на русском языке. Он должен быть самостоятельным текстом, который можно почти сразу публиковать. Нужны сильное первое предложение, логичное развитие мысли, конкретика под нишу и аудиторию, естественный CTA. Не пиши мета-комментарии о том, как написать пост. Не используй клише и искусственные фразы.`,
  stories: `Создай полноценную серию сторис. Для каждой сторис укажи номер, цель, конкретный текст на экране/для речи, визуальное действие и интерактивный элемент, если он уместен. Последовательность должна вести человека к цели, а не состоять из одинаковых карточек.`,
  ideas: `Придумай 10 действительно разных контент-идей под бренд. Для каждой дай: название идеи, конкретный угол раскрытия, hook и рекомендуемый формат. Идеи должны отличаться механикой и смыслом: экспертность, кейс, ошибка, миф, сравнение, история, возражение, демонстрация, вовлечение и/или продажа — выбирай то, что подходит бренду. Не повторяй одну и ту же мысль разными словами.`,
  content_factory: `Собери содержательный контент-сет под одну тему и цель. Для каждого выбранного формата создай отдельный материал: Reels — идея + hook + короткий сценарий с репликами; Посты — конкретная тема + hook + структура и готовый текст; Stories — последовательность из 5 кадров с текстом и механикой. Не повторяй один шаблон между форматами. Каждый элемент должен решать цель бренда.`
};

function json(res,status,data){res.status(status).setHeader("Content-Type","application/json; charset=utf-8");res.end(JSON.stringify(data));}

export default async function handler(req,res){
  if(req.method !== "POST") return json(res,405,{error:"Method Not Allowed"});
  if(!process.env.OPENAI_API_KEY) return json(res,500,{error:"AI не подключён: на сервере не задан OPENAI_API_KEY."});

  try{
    const body=req.body||{};
    const task=String(body.task||"");
    if(!TASKS[task]) return json(res,400,{error:"Неизвестный тип генерации."});

    const project=String(body.project||"").slice(0,4000);
    const details=Object.entries(body)
      .filter(([key])=>!['task','project'].includes(key))
      .map(([key,value])=>`${key}: ${typeof value==='string'?value.slice(0,1500):JSON.stringify(value)}`)
      .join("\n");

    const instructions=`Ты — сильный senior SMM-стратег, копирайтер и контент-продюсер. Работаешь для реального бизнеса, поэтому качество важнее красивых общих слов.

КОНТЕКСТ ПРОЕКТА:
${project||"Контекст проекта не указан."}

ЗАДАЧА:
${TASKS[task]}

ВХОДНЫЕ ДАННЫЕ:
${details}

ОБЩИЕ ПРАВИЛА:
- Пиши на русском языке, если пользователь не попросил другое.
- Не выдумывай факты о бизнесе, цены, адреса, акции, цифры или гарантии. Если факта нет, формулируй нейтрально.
- Не начинай с «В современном мире», «Знакомая ситуация», «Сегодня я хочу рассказать» и подобных заезженных вступлений.
- Не повторяй тему пользователя как заголовок без добавления смысла.
- Не используй канцелярит и чрезмерные эмодзи.
- Пиши естественно, как сильный человек из SMM-команды, а не как генератор шаблонов.
- Делай контент конкретным для указанной ниши, ЦА, tone of voice и цели.
- Если данных мало, используй разумные маркетинговые предположения, но не выдавай их за факты.
- Верни только готовый результат без вступления о своих действиях.`;

    const response=await fetch("https://api.openai.com/v1/responses",{
      method:"POST",
      headers:{"Content-Type":"application/json","Authorization":`Bearer ${process.env.OPENAI_API_KEY}`},
      body:JSON.stringify({model:MODEL,instructions,input:`Сгенерируй результат сейчас.\n\n${instructions}`,store:false})
    });

    const data=await response.json();
    if(!response.ok){
      const message=data?.error?.message||"OpenAI API вернул ошибку.";
      return json(res,response.status,{error:message});
    }
    const text=data.output_text || (data.output||[]).flatMap(x=>x.content||[]).filter(x=>x.type==="output_text").map(x=>x.text).join("\n");
    if(!text) return json(res,502,{error:"AI не вернул текстовый результат."});
    return json(res,200,{text});
  }catch(error){
    console.error(error);
    return json(res,500,{error:"Не удалось связаться с AI-сервисом. Проверь подключение и настройки сервера."});
  }
}
